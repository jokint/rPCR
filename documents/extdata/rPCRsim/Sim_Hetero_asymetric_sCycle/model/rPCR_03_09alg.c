  if (measure_time_flag) rt_tick(SIM_TIMER_ALGEBRAICS);
#endif
  data->simulationInfo->callStatistics.functionAlgebraics++;

  rPCR_03_function_savePreSynchronous(data, threadData);
  
  functionAlg_system0(data, threadData);

